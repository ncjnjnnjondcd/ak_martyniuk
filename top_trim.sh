
#!/bin/bash

# Кількість рядків: береться з першого параметра скрипта
# якщо параметр не заданий то використовується значення 5
n=${1:-5}

# Імя файлу куди зберігається результат
output_file="top_output.txt"

# Перенаправити результат виконання top у файл
top -bn1 > "$output_file"

# Обрізати файл залишивши тільки перші n рядків
head -n "$n" "$output_file" > "${output_file}.tmp" && mv "${output_file}.tmp" "$output_file"

echo "Готово. Файл $output_file містить перші $n рядків."
